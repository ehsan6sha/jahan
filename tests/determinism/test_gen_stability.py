"""World generation stays byte-identical when new attributes are added.

`fixtures/gen_columns_schema5.json` holds per-column sha256 hashes of worlds generated by the code as it
was before political alignment existed (schema 5).  New columns use their own hash streams, so every
column that existed then must still come out identical.  Public figures are excluded: their rows carry
roster values (approval, alignment) that are data, not generation.
"""

import hashlib
import json
from pathlib import Path

import numpy as np

from jahan.config import RunConfig
from jahan.gen.world_gen import generate_world
from jahan.store.snapshot import TABLES

FIXTURE = Path(__file__).parent / "fixtures" / "gen_columns_schema5.json"
WORLDS = {
    "usa_ind_bra": RunConfig(n_agents=1200, countries=["USA", "IND", "BRA"], seed=11, start_date="2026-10-13"),
    "all_eight": RunConfig(
        n_agents=2000,
        countries=["USA", "BRA", "DEU", "NGA", "IRN", "IND", "CHN", "IDN"],
        seed=3,
        start_date="2026-10-13",
    ),
}


def column_hashes(world) -> dict[str, str]:  # noqa: ANN001
    out = {}
    ordinary = ~world.pop["is_notable"]
    for prefix, (attr, _spec) in TABLES.items():
        if attr not in ("pop", "households", "workplaces", "edges", "channels"):
            continue
        table = getattr(world, attr)
        for name in table.columns():
            col = np.ascontiguousarray(table[name][ordinary] if attr == "pop" else table[name])
            out[f"{prefix}{name}"] = hashlib.sha256(col.tobytes()).hexdigest()
    return out


def write_fixture() -> None:
    """Run once on the pre-change code: `uv run python -c "from tests.determinism.test_gen_stability import
    write_fixture; write_fixture()"`."""
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    data = {name: column_hashes(generate_world(cfg)) for name, cfg in WORLDS.items()}
    FIXTURE.write_text(json.dumps(data, indent=1, sort_keys=True), encoding="utf-8")


def test_existing_columns_are_unchanged():
    expected = json.loads(FIXTURE.read_text(encoding="utf-8"))
    for name, cfg in WORLDS.items():
        got = column_hashes(generate_world(cfg))
        changed = sorted(k for k, v in expected[name].items() if got.get(k) != v)
        assert not changed, f"{name}: generation changed for {changed}"
