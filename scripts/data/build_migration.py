"""Extract a bilateral migrant-stock matrix from UN DESA International Migrant Stock 2024.

    uv run python -I -X utf8 scripts/data/build_migration.py \
        --xlsx data/raw/undesa_ims2024/undesa_pd_2024_ims_stock_by_sex_destination_and_origin.xlsx \
        --out data/generated/migration/stock_2024.yaml --countries USA,BRA,DEU,NGA,IRN,IND,CHN,IDN

Writes stock[destination][origin] (people born in origin living in destination, both sexes,
mid-2024) plus each destination's total immigrant stock.  Values are copied without modelling.
"""

from __future__ import annotations

import argparse
import datetime as dt
from pathlib import Path

import openpyxl
import yaml

M49 = {"USA": 840, "BRA": 76, "DEU": 276, "NGA": 566, "IRN": 364, "IND": 356, "CHN": 156, "IDN": 360}
URL = (
    "https://www.un.org/development/desa/pd/sites/www.un.org.development.desa.pd/files/"
    "undesa_pd_2024_ims_stock_by_sex_destination_and_origin.xlsx"
)
WORLD = 900


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--xlsx", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--countries", default=",".join(M49))
    a = ap.parse_args()
    countries = [c.strip().upper() for c in a.countries.split(",")]
    codes = {M49[c]: c for c in countries}
    wb = openpyxl.load_workbook(a.xlsx, read_only=True, data_only=True)
    ws = wb["Table 1"]
    header_row = None
    col_2024 = None
    stock: dict[str, dict[str, int]] = {c: {} for c in countries}
    total_immigrants: dict[str, int] = {}
    for row in ws.iter_rows(values_only=True):
        if header_row is None:
            if row and row[0] == "Index":
                header_row = row
                col_2024 = list(row).index(2024)  # first 2024 column = both sexes
            continue
        dest, origin = row[4], row[6]
        if not isinstance(dest, int) or not isinstance(origin, int):
            continue
        value = row[col_2024]
        if value in (None, "..", ""):
            continue
        if dest in codes and origin in codes and dest != origin:
            stock[codes[dest]][codes[origin]] = int(value)
        if dest in codes and origin == WORLD:
            total_immigrants[codes[dest]] = int(value)
    doc = {
        "source": "UN DESA Population Division, International Migrant Stock 2024 (POP/DB/MIG/Stock/Rev.2024), Table 1",
        "url": URL,
        "license": "CC BY 3.0 IGO",
        "year": 2024,
        "retrieved": dt.date.today().isoformat(),
        "stock": stock,
        "total_immigrants": total_immigrants,
    }
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(
        "# Generated by scripts/data/build_migration.py. Do not edit by hand.\n" + yaml.safe_dump(doc, sort_keys=False),
        encoding="utf-8",
    )
    for d in countries:
        pairs = ", ".join(f"{o}={n:,}" for o, n in sorted(stock[d].items(), key=lambda kv: -kv[1]))
        print(f"{d} (all immigrants {total_immigrants.get(d, 0):,}): {pairs}")


if __name__ == "__main__":
    main()
