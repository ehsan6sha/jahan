"""Fetch World Bank World Development Indicators for the simulated countries.

    uv run python -I scripts/data/build_wdi.py --out data/generated/wdi --countries USA,BRA,DEU,NGA,IRN,IND,CHN,IDN

Writes ``{ISO3}.yaml`` with the latest non-missing value (and its year) of each indicator.
The API is public (CC BY 4.0).  Values are copied without modelling.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import urllib.request
from pathlib import Path

import yaml

API = "https://api.worldbank.org/v2/country/{countries}/indicator/{indicator}?format=json&date={start}:{end}&per_page=1000"
INDICATORS = {
    "SP.URB.TOTL.IN.ZS": "urban_pct",
    "IT.NET.USER.ZS": "internet_users_pct",
    "PA.NUS.FCRF": "fx_local_per_usd",
    "NY.GNP.PCAP.CD": "gni_per_capita_usd",
    "SL.UEM.TOTL.ZS": "unemployment_pct_ilo_modelled",
    "SL.EMP.TOTL.SP.ZS": "employment_to_population_15plus_pct",
    "SL.TLF.CACT.FE.ZS": "female_labour_participation_15plus_pct",
    "SE.TER.ENRR": "tertiary_gross_enrolment_pct",
    "ST.INT.DPRT": "international_departures",
    "SP.POP.TOTL": "population_total",
}


# travel collapsed in 2020-2021; use the latest pre-pandemic year as the baseline for normal travel
PRE_PANDEMIC_MAX_YEAR = {"ST.INT.DPRT": 2019}


def fetch(indicator: str, countries: list[str], start: int, end: int) -> list[dict]:
    url = API.format(countries=";".join(countries), indicator=indicator, start=start, end=end)
    with urllib.request.urlopen(url, timeout=60) as r:  # noqa: S310 (fixed https host)
        payload = json.loads(r.read().decode("utf-8"))
    if not isinstance(payload, list) or len(payload) < 2 or payload[1] is None:
        return []
    return payload[1]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--countries", default="USA")
    ap.add_argument("--start", type=int, default=2015)
    ap.add_argument("--end", type=int, default=dt.date.today().year)
    a = ap.parse_args()
    countries = [c.strip().upper() for c in a.countries.split(",")]
    docs = {
        c: {
            "iso3": c,
            "source": "World Bank, World Development Indicators (API v2)",
            "license": "CC BY 4.0",
            "retrieved": dt.date.today().isoformat(),
            "indicators": {},
        }
        for c in countries
    }
    for code, name in INDICATORS.items():
        rows = fetch(code, countries, a.start, a.end)
        latest: dict[str, tuple[int, float]] = {}
        max_year = PRE_PANDEMIC_MAX_YEAR.get(code)
        for r in rows:
            iso, val = r.get("countryiso3code"), r.get("value")
            if iso in docs and val is not None:
                year = int(r["date"])
                if max_year is not None and year > max_year:
                    continue
                if iso not in latest or year > latest[iso][0]:
                    latest[iso] = (year, float(val))
        for iso, (year, val) in latest.items():
            docs[iso]["indicators"][name] = {"value": round(val, 6), "year": year, "code": code}
    a.out.mkdir(parents=True, exist_ok=True)
    for c, doc in docs.items():
        (a.out / f"{c}.yaml").write_text(
            "# Generated by scripts/data/build_wdi.py. Do not edit by hand.\n" + yaml.safe_dump(doc, sort_keys=False),
            encoding="utf-8",
        )
        found = ", ".join(f"{k}={v['value']:.4g} ({v['year']})" for k, v in doc["indicators"].items())
        print(f"{c}: {found}")


if __name__ == "__main__":
    main()
